const { chromium } = require('../.runtime/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:8765';
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1100}});
  const failures=[];const checks=[]; page.on('pageerror',e=>failures.push(e.message));
  await page.goto(base+'/#assistant');await page.locator('#assistant').waitFor({state:'visible'});
  await page.getByRole('heading',{name:'What would you like to check?'}).count();
  await page.screenshot({path:'evaluations/ui-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Lock a misplaced card'}).click();
  await page.locator('.answer').waitFor();
  assert.match(await page.locator('.answer').innerText(),/15 days/);
  const link=page.locator('.answer .sources a').first();
  assert.equal(await link.getAttribute('href'),'https://www.westpac.com.au/personal-banking/online-banking/making-the-most/lock-card/');
  assert.equal(await link.getAttribute('rel'),'noopener noreferrer');checks.push('chat and official source link');
  await page.locator('#question').fill('How long?');await page.locator('#question').press('Enter');
  await page.waitForFunction(()=>document.querySelectorAll('.answer').length===2);
  assert.match(await page.locator('.answer').last().innerText(),/15 days/);checks.push('keyboard send and multi-turn context');
  await page.locator('#question').fill('How do I lock my card? email test@example.test OTP 928173 password MySecret_12');
  await page.locator('#question').press('Enter');await page.waitForFunction(()=>document.querySelectorAll('.answer').length===3);
  assert.doesNotMatch(await page.locator('body').innerText(),/test@example.test|928173|MySecret_12/);checks.push('sensitive input absent from transcript');
  await page.locator('.fixture-panel summary').click();await page.locator('#fixture').selectOption('conflict');
  await page.locator('#question').fill('How do I lock my card?');await page.locator('#question').press('Enter');
  await page.waitForFunction(()=>document.querySelectorAll('.answer').length===4);
  assert.match(await page.locator('.answer').last().innerText(),/SYNTHETIC FIXTURE/);assert.match(await page.locator('.answer').last().innerText(),/disagree/);checks.push('labelled conflict fixture');
  await page.locator('#fixture').selectOption('none');await page.locator('#mode').selectOption('openai');
  assert.match(await page.locator('#cloud-disclosure').innerText(),/OpenAI/);checks.push('mode switching');
  const modelStatus=await (await page.request.get(base+'/api/status')).json();
  if(modelStatus.provider.available){
    await page.locator('#question').fill('How do I lock my card?');await page.locator('#question').press('Enter');
    await page.waitForFunction(()=>document.querySelectorAll('.answer').length===5,{},{timeout:55000});
    assert.match(await page.locator('.answer').last().innerText(),/OpenAI API called/);
    assert.match(await page.locator('.answer').last().innerText(),/15 days/);checks.push('real OpenAI API answer through browser');
  } else {
    await page.locator('#question').fill('How do I lock my card?');await page.locator('#question').press('Enter');
    await page.waitForFunction(()=>document.querySelectorAll('.answer').length===5);
    assert.match(await page.locator('.answer').last().innerText(),/OPENAI_API_KEY/);
    assert.doesNotMatch(await page.locator('.answer').last().innerText(),/15 days/);checks.push('OpenAI missing key fails explicitly without fallback');
  }
  assert.equal(await page.locator('#cloud-disclosure').isVisible(),true);checks.push('cloud transfer disclosure');
  await page.route('**/api/chat',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'Synthetic browser transport failure'})}));
  await page.locator('#question').fill('How do I lock my card?');await page.locator('#question').press('Enter');
  await page.locator('#messages').getByText('Synthetic browser transport failure',{exact:true}).waitFor();
  assert.equal(await page.locator('#send').isDisabled(),false);await page.unroute('**/api/chat');checks.push('transport error clears loading');
  await page.locator('.evidence-panel summary').click();assert.equal(await page.locator('.panel-body').isVisible(),false);await page.locator('.evidence-panel summary').click();checks.push('collapsible trace');
  await page.locator('[data-view="knowledge"]').click();await page.locator('.file-card').first().waitFor();
  assert.ok(await page.locator('.file-card').count()>=10);await page.locator('.file-card').first().click();await page.locator('.chunk-card').first().waitFor();
  await page.getByRole('tab',{name:'Raw file'}).click();await page.locator('.raw-file').waitFor();await page.getByRole('button',{name:'All files'}).click();checks.push('knowledge files, chunks and raw file');
  await page.locator('[data-view="lab"]').click();await page.locator('#run-tests').click();
  await page.waitForFunction(()=>document.querySelector('#eval-status').textContent.startsWith('Run complete'),{},{timeout:30000});
  assert.equal(await page.locator('#eval-results tbody tr').count(),23);assert.match(await page.locator('#eval-results').innerText(),/23\/23/);checks.push('actual evaluation button and measured results');
  await page.screenshot({path:'evaluations/ui-lab.png',fullPage:true});
  await page.locator('[data-view="assistant"]').click();await page.locator('#reset').click();
  assert.equal(await page.locator('.answer').count(),0);checks.push('reset conversation');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'evaluations/ui-mobile.png',fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.locator('#question').focus();await page.keyboard.press('Tab');assert.equal(await page.locator('#send').evaluate(el=>el===document.activeElement),true);checks.push('390px viewport and keyboard focus');
  await browser.close();
  assert.deepEqual(failures,[]);
  fs.writeFileSync('evaluations/ui-results.json',JSON.stringify({executed_at:new Date().toISOString(),browser:'Installed Google Chrome via Playwright',checks,console_errors:failures,passed:true},null,2));
  console.log(JSON.stringify({passed:true,checks},null,2));
})().catch(error=>{console.error(error);process.exit(1)});
